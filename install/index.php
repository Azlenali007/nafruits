// Step 2 & 3: DB Connection & Schema Setup
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['test_and_install_db'])) {
    $dbHost = trim($_POST['db_host'] ?? '127.0.0.1');
    $dbPort = trim($_POST['db_port'] ?? '3306');
    $dbName = trim($_POST['db_name'] ?? 'nafresh_db');
    $dbUser = trim($_POST['db_user'] ?? 'root');
    $dbPass = $_POST['db_pass'] ?? '';

    $adminName = trim($_POST['admin_name'] ?? 'NA Fresh Admin');
    $adminEmail = trim($_POST['admin_email'] ?? 'admin@nafresh.com');
    $adminPass = trim($_POST['admin_pass'] ?? 'admin123');

    try {
        // Test connection
        $dsn = "mysql:host={$dbHost};port={$dbPort};charset=utf8mb4";
        $pdo = new PDO($dsn, $dbUser, $dbPass, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION
        ]);

        // Create database if not exists
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        $pdo->exec("USE `{$dbName}`");

        // Import Schema
        $schemaSql = file_get_contents(dirname(__DIR__) . '/database/schema.sql');
        if ($schemaSql) {
            $pdo->exec($schemaSql);
        }

        // Import Seeds
        $seedsSql = file_get_contents(dirname(__DIR__) . '/database/seeds.sql');
        if ($seedsSql) {
            $pdo->exec($seedsSql);
        }

        // Update or Insert Custom Admin
        if (!empty($adminEmail) && !empty($adminPass)) {
            $adminHash = password_hash($adminPass, PASSWORD_BCRYPT);
            $stmt = $pdo->prepare("UPDATE admins SET name = ?, email = ?, password_hash = ? WHERE id = 1");
            $stmt->execute([$adminName, $adminEmail, $adminHash]);
        }

        // Write config.local.php
        $configContent = "<?php\n"
            . "// NA Fresh Local Configuration generated by Installer on " . date('Y-m-d H:i:s') . "\n"
            . "define('DB_HOST', " . var_export($dbHost, true) . ");\n"
            . "define('DB_PORT', " . var_export($dbPort, true) . ");\n"
            . "define('DB_NAME', " . var_export($dbName, true) . ");\n"
            . "define('DB_USER', " . var_export($dbUser, true) . ");\n"
            . "define('DB_PASS', " . var_export($dbPass, true) . ");\n"
            . "define('DB_CHARSET', 'utf8mb4');\n";

        file_put_contents(dirname(__DIR__) . '/config.local.php', $configContent);

        // Lock installer
        file_put_contents($lockFile, "Installed on " . date('c'));

        header('Location: /install/index.php?step=5');
        exit;

    } catch (Exception $e) {
        $error = "Database Error: " . $e->getMessage();
    }
}
